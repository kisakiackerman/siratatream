export async function translateSubtitlesWithGemini(
  mediaId: string,
  lines: SubtitleLine[],
  targetLang: string = "fr",
  contextTitle: string = ""
): Promise<Record<string, string>> {
  const cacheKey = `${mediaId}_${targetLang}`;
  if (translationsMemoryCache.has(cacheKey)) {
    return translationsMemoryCache.get(cacheKey)!;
  }

  try {
    const res = await fetch("/api/ai/translate-lyrics", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        lines: lines.map((l) => ({
          id: l.id,
          text: l.text,
          arabicText: l.arabicText,
          translation: l.translation,
        })),
        targetLang,
        contextTitle,
      }),
    });

    if (!res.ok) {
      throw new Error(`Translation request failed: ${res.statusText}`);
    }

    const data = await res.json();
    const translationMap: Record<string, string> = {};

    if (data.translations && Array.isArray(data.translations)) {
      for (const item of data.translations) {
        if (item.id && item.text) {
          translationMap[item.id] = item.text;
        }
      }
    }

    // Fill any missing keys with fallback
    for (const l of lines) {
      if (!translationMap[l.id]) {
        translationMap[l.id] = l.translation || l.text;
      }
    }

    translationsMemoryCache.set(cacheKey, translationMap);
    return translationMap;
  } catch (err) {
    console.error("Gemini lyrics translation error:", err);
    const fallbackMap: Record<string, string> = {};
    for (const l of lines) {
      fallbackMap[l.id] = l.translation || l.text;
    }
    return fallbackMap;
  }
}

